"""Write the request-field section of docs/AI_REFERENCE.md from the wire policy table.

    uv run python tools/generate_wire_reference.py           # write the section
    uv run python tools/generate_wire_reference.py --check   # exit 1 when the section differs

The section sits between the two marker comments below; everything else in the page is written
by hand. The table it renders is ``ayaka.entrypoints.wire.policy.ENDPOINTS``, the one the server
applies to every request, so the page cannot say a field is read when the server refuses it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Final

from ayaka.entrypoints.wire.policy import wire_reference

ROOT: Final = Path(__file__).resolve().parents[1]
TARGET: Final = ROOT / "docs" / "AI_REFERENCE.md"
BEGIN: Final = "<!-- wire-policy:begin (generated by tools/generate_wire_reference.py) -->"
END: Final = "<!-- wire-policy:end -->"


def render(page: str) -> str:
    """``page`` with its generated section replaced by the table as it is now.

    Raises:
        ValueError: If the page does not have both markers, in order.
    """
    start, end = page.find(BEGIN), page.find(END)
    if start < 0 or end < start:
        raise ValueError(f"{TARGET.name} needs the markers {BEGIN!r} and {END!r}, in that order")
    return page[: start + len(BEGIN)] + "\n\n" + wire_reference() + "\n" + page[end:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write the wire section of AI_REFERENCE.md.")
    parser.add_argument("--check", action="store_true", help="exit 1 if the page differs")
    args = parser.parse_args(argv)
    page = TARGET.read_text(encoding="utf-8")
    wanted = render(page)
    if args.check:
        if wanted != page:
            print(f"{TARGET} is out of date: run uv run python tools/generate_wire_reference.py")
            return 1
        return 0
    TARGET.write_text(wanted, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
