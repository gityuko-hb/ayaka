"""Tokenizing a chat that contains embedded media (images, audio, ...).

Media content becomes a run of *placeholder* tokens whose embeddings are filled in
later, so the text around each media item must be tokenized separately; otherwise a
token could straddle the boundary::

    chat --render--> "...<|im_start|>user\\n[MEDIA0] describe it<|im_end|>..."
                      |_______ text _______|marker|__________ text __________|
                                 |                              |
                      encode as RenderedInput       encode as RenderedInput
                                 v                              v
                      [ids ...] + [placeholder] * count + [ids ...]  --> validated once

Markers are generated by the caller, never read from user text, and the chat template
must keep each one exactly once and in order.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from ayaka.tokenizers.contracts import (
    ChatInput,
    EncodeOptions,
    RenderedInput,
    TokenIdsInput,
    encode_input_weight,
)
from ayaka.tokenizers.errors import TokenizerOverloaded

if TYPE_CHECKING:
    from ayaka.configs.tokenizer import EncodeResult
    from ayaka.tokenizers.service import TokenizerService

__all__ = ["encode_media_chat"]


def encode_media_chat(
    service: TokenizerService,
    chat: ChatInput,
    options: EncodeOptions,
    markers: tuple[tuple[str, int], ...],
    placeholder: int,
) -> tuple[EncodeResult, tuple[int, ...]]:
    """Encode ``chat`` with each marker expanded into placeholder tokens.

    Args:
        service: The tokenizer service that renders and encodes.
        chat: The conversation; its template must preserve every marker.
        options: Encode options. ``truncate`` must be off, because cutting the
            prompt could cut through an embedding span.
        markers: ``(marker_text, token_count)`` pairs in order of appearance.
        placeholder: Token id used to fill each embedding span.

    Returns:
        The validated result and the offset in the final ids where each span starts.

    Raises:
        ValueError: If truncation is requested, the placeholder id is invalid, or
            the template dropped, duplicated or reordered a marker.
        TokenizerOverloaded: If the chat or its rendered text exceeds the byte budget.
    """
    if options.truncate:
        raise ValueError("media chat cannot truncate embedding spans")
    if type(placeholder) is not int or not 0 <= placeholder < service.model_vocab_size:  # pyright: ignore[reportUnnecessaryIsInstance]
        raise ValueError("invalid media placeholder token")
    budget = service.config.encode_max_pending_bytes
    if encode_input_weight(chat) > budget:
        raise TokenizerOverloaded("media chat input exceeds byte budget")
    rendered = service.render_chat(chat)
    if len(rendered.encode()) > budget:
        raise TokenizerOverloaded("rendered media chat exceeds byte budget")

    tokens: list[int] = []
    starts: list[int] = []
    cursor = 0
    for marker, count in markers:
        if not marker or type(count) is not int or count < 1 or rendered.count(marker) != 1:  # pyright: ignore[reportUnnecessaryIsInstance]
            raise ValueError("chat template must preserve each media placeholder exactly once")
        end = rendered.index(marker)
        if end < cursor:
            raise ValueError("chat template reordered media placeholders")
        if text := rendered[cursor:end]:
            tokens.extend(service.encode(RenderedInput(text), options).token_ids)
        starts.append(len(tokens))
        tokens.extend([placeholder] * count)
        cursor = end + len(marker)
    if text := rendered[cursor:]:
        tokens.extend(service.encode(RenderedInput(text), options).token_ids)
    return service.encode(TokenIdsInput(tuple(tokens)), options), tuple(starts)
